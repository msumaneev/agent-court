"""
Adapter for Google Antigravity session transcripts.
"""

from __future__ import annotations

import json
import os
from datetime import datetime, timezone, timedelta
from pathlib import Path
from typing import Dict, Generator, List, Optional, Tuple

from agent_court.core.models import StepEvent


class AntigravityAdapter:
    """
    Ingests and normalizes transcripts generated by Google Antigravity.
    Path pattern: ~/.gemini/antigravity/brain/<session_id>/.system_generated/logs/transcript.jsonl
    """

    def __init__(self, base_dir: Optional[str] = None):
        if base_dir:
            self.base_dir = Path(base_dir).expanduser().resolve()
        else:
            home = Path.home()
            self.base_dir = (home / ".gemini" / "antigravity" / "brain").resolve()

    def discover_transcripts(self, days: int = 30) -> List[Tuple[str, Path]]:
        """
        Discovers session transcripts updated within the specified number of days.
        Returns a list of (session_id, transcript_path).
        """
        if not self.base_dir.exists():
            return []

        cutoff_time = datetime.now(timezone.utc) - timedelta(days=days)
        results: List[Tuple[str, Path]] = []

        try:
            for entry in self.base_dir.iterdir():
                if entry.is_dir():
                    transcript_file = entry / ".system_generated" / "logs" / "transcript.jsonl"
                    if transcript_file.exists():
                        mtime = datetime.fromtimestamp(transcript_file.stat().st_mtime, tz=timezone.utc)
                        if mtime >= cutoff_time:
                            results.append((entry.name, transcript_file))
        except Exception:
            pass

        # Sort from most recent to oldest
        results.sort(key=lambda x: x[1].stat().st_mtime, reverse=True)
        return results

    def parse_transcript(self, file_path: Path) -> List[StepEvent]:
        """
        Streaming parser for an individual transcript.jsonl file.
        """
        events: List[StepEvent] = []
        if not file_path.exists():
            return events

        with open(file_path, "r", encoding="utf-8", errors="replace") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                try:
                    data = json.loads(line)
                    event = StepEvent(
                        step_index=data.get("step_index", len(events)),
                        source=data.get("source", "UNKNOWN"),
                        type=data.get("type", "GENERIC"),
                        status=data.get("status", "DONE"),
                        content=data.get("content"),
                        thinking=data.get("thinking"),
                        tool_calls=data.get("tool_calls", []),
                        error=data.get("error"),
                        created_at=data.get("created_at"),
                    )
                    events.append(event)
                except Exception:
                    continue

        return events

    def load_sessions(self, days: int = 30) -> Generator[Tuple[str, List[StepEvent]], None, None]:
        """
        Generator yielding (session_id, steps) for all recent sessions.
        """
        transcripts = self.discover_transcripts(days=days)
        for session_id, path in transcripts:
            steps = self.parse_transcript(path)
            if steps:
                yield session_id, steps
